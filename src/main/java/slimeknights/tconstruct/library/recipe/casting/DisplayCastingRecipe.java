package slimeknights.tconstruct.library.recipe.casting;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.RequiredArgsConstructor;
import lombok.Setter;
import lombok.experimental.Accessors;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.crafting.Ingredient;
import net.neoforged.neoforge.fluids.FluidStack;
import net.neoforged.neoforge.fluids.crafting.SizedFluidIngredient;
import slimeknights.mantle.recipe.NamedRecipe;
import slimeknights.tconstruct.library.recipe.casting.material.MaterialCastingLookup;
import slimeknights.tconstruct.library.recipe.display.ItemVisible;

import javax.annotation.Nullable;
import java.util.List;

/**
 * Simple implementation of a display casting recipe, generated by certain recipe types
 */
@Getter
@RequiredArgsConstructor(access = AccessLevel.PRIVATE)
public final class DisplayCastingRecipe implements IDisplayableCastingRecipe {
  private final List<ItemStack> castItems;
  private final List<FluidStack> fluids;
  private final List<ItemStack> outputs;
  private final int coolingTime;
  private final boolean consumed;
  @Accessors(fluent = true)
  private final boolean linkCastToOutput;
  @Accessors(fluent = true)
  private final boolean linkFluidsToOutput;
  private final boolean coolingTimeDynamic;
  @Accessors(fluent = true)
  private final boolean showUnfocused;
  @Nullable
  private final ItemVisible isVisible;

  @Override
  public boolean hasCast() {
    return !castItems.isEmpty();
  }

  @Override
  public int getCoolingTime(FluidStack fluid) {
    return MaterialCastingLookup.getCoolingTime(fluid, coolingTime);
  }

  @Override
  public boolean isFiltered() {
    return !showUnfocused || isVisible != null;
  }

  @Override
  public boolean isVisibleFromItem(ItemStack focus, boolean output) {
    return isVisible == null || isVisible.isVisibleFromItem(focus, output);
  }


  /* Builder */

  /** Creates a new builder instance */
  public static Builder id(ResourceLocation id, List<ResourceLocation> parent) {
    return new Builder(id, parent);
  }

  /** Creates a new builder instance */
  public static Builder id(ResourceLocation id) {
    return id(id, List.of(id));
  }

  @Setter
  @Accessors(fluent = true)
  @RequiredArgsConstructor
  public static class Builder {
    private final ResourceLocation id;
    private final List<ResourceLocation> parent;
    private List<ItemStack> casts = List.of();
    private List<FluidStack> fluids = List.of();
    private List<ItemStack> results = List.of();
    private int coolingTime = 1;
    private boolean consumed = false;
    private boolean linkCastToOutput = true;
    private boolean linkFluidsToOutput = false;
    /** If true, this is a material casting recipe and the casting time should animate between fluids. {@link #coolingTime} is used as a fallback for unknown fluids. */
    private boolean materialCoolingTime = false;
    // filtering
    private boolean showUnfocused = true;
    /** Checks if the recipe is visible given the focus stack */
    @Nullable
    private ItemVisible isVisible;

    /** Sets the given ingredient as the cast */
    public Builder cast(Ingredient cast) {
      return casts(List.of(cast.getItems()));
    }

    /** Sets the given cast to the builder */
    public Builder cast(ItemStack cast) {
      return casts(List.of(cast));
    }

    /** Sets the given cast to the builder */
    public Builder fluid(FluidStack fluid) {
      return fluids(List.of(fluid));
    }

    /** Sets the given cast to the builder */
    public Builder fluid(SizedFluidIngredient fluid) {
      return fluids(List.of(fluid.getFluids()));
    }

    /** Sets the given output to the builder */
    public Builder result(ItemStack output) {
      return results(List.of(output));
    }

    /** Sets the cast to consumed */
    public Builder consumed() {
      return consumed(true);
    }

    /** Sets this to a material casting recipe. Assumes that {@link #fluids(List)} is set to a list of fluids for each item in {@link #results(List)} */
    public Builder materialCasting(boolean composite) {
      return materialCoolingTime(true).linkFluidsToOutput(true).linkCastToOutput(composite);
    }


    /* Linking */

    /** Sets the builder to link the casts to output */
    public Builder linkCastToOutput() {
      this.linkCastToOutput = true;
      this.linkFluidsToOutput = false;
      return this;
    }

    /** Sets the builder to link the fluids to output */
    public Builder linkFluidsToOutput() {
      this.linkCastToOutput = false;
      this.linkFluidsToOutput = true;
      return this;
    }

    /** Sets the builder to link the casts to output */
    public Builder linkAllToOutput() {
      this.linkCastToOutput = true;
      this.linkFluidsToOutput = true;
      return this;
    }

    /** Sets the builder to link the casts to output */
    public Builder unlinkOutput() {
      this.linkCastToOutput = false;
      this.linkFluidsToOutput = false;
      return this;
    }

    /** Builds the final recipe */
    public NamedRecipe<IDisplayableCastingRecipe> build() {
      if (fluids.isEmpty()) throw new IllegalStateException("Fluids cannot be empty");
      if (results.isEmpty()) throw new IllegalStateException("Results cannot be empty");
      return NamedRecipe.of(id, parent, new DisplayCastingRecipe(casts, fluids, results, coolingTime, consumed, linkCastToOutput, linkFluidsToOutput, materialCoolingTime && fluids.size() > 1, showUnfocused, isVisible));
    }
  }
}
